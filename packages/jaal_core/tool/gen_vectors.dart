// Generates protocol/test-vectors/v1.json: deterministic inputs and expected
// outputs that every Jaal implementation (Dart, the TypeScript PWA, ...) must
// reproduce byte-for-byte.
//
//   dart run tool/gen_vectors.dart
import 'dart:convert';
import 'dart:io';
import 'dart:typed_data';

import 'package:jaal_core/jaal_core.dart';

Future<void> main() async {
  final rootSeed = Uint8List.fromList(List.generate(32, (i) => i));
  final deviceSeed = Uint8List.fromList(List.generate(32, (i) => 32 + i));
  const created = 1767225600000;

  final root = await RootIdentity.fromSeed(rootSeed);
  final me = await LocalIdentity.create(root, deviceSeed: deviceSeed, now: created);

  final canonical = [
    {'a': 1, 'B': [true, null, 'x'], 'é': {'z': 0, 'y': -1}},
    'quote" backslash\\ newline\n tab\t ctrl\u0001 emoji😀',
    {'😀': 1, 'z': 2, 'é': 3, 'A': 4},
  ];

  final bodies = <(String, Map<String, Object?>)>[
    (EventType.deviceCert, me.cert.toJson()),
    (
      EventType.profile,
      Bodies.profile(name: 'Maya', handle: 'maya', bio: 'off grid', dmKey: me.dmPublicKey)
    ),
    (EventType.post, Bodies.post(text: 'no wifi? no problem.')),
  ];

  final events = <Map<String, Object?>>[];
  String? prev;
  for (var i = 0; i < bodies.length; i++) {
    final (type, body) = bodies[i];
    final e = await SignedEvent.create(
      device: me.device,
      seq: i + 1,
      prev: prev,
      lamport: i + 1,
      ts: created + i * 1000,
      type: type,
      body: body,
    );
    prev = e.id;
    events.add({
      'body': body,
      'bodyCanonical': CanonicalJson.encode(body),
      'event': e.toJson(),
      'unsignedCanonical': CanonicalJson.encode(e.unsignedJson()),
      'id': e.id,
    });
  }

  final out = {
    'version': 1,
    'note': 'Generated by packages/jaal_core/tool/gen_vectors.dart. Do not edit.',
    'canonicalJson': [
      for (final c in canonical) {'input': c, 'output': CanonicalJson.encode(c)}
    ],
    'identity': {
      'rootSeed': b64(rootSeed),
      'recoveryPhrase': root.recoveryPhrase,
      'rootPublicKey': root.id,
      'fingerprint': root.fingerprint,
      'dmPublicKey': b64(root.dm.publicKey),
      'dmHint': me.dmHint,
      'selfKey': b64(root.selfKey),
      'deviceSeed': b64(deviceSeed),
      'devicePublicKey': me.feedId,
      'deviceCert': me.cert.toJson(),
    },
    'events': events,
  };

  final file = File('../../protocol/test-vectors/v1.json');
  await file.parent.create(recursive: true);
  await file.writeAsString(
      '${const JsonEncoder.withIndent('  ').convert(out)}\n');
  stdout.writeln('wrote ${file.path}');
}
