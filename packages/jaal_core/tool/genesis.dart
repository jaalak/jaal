// Generates the three genesis moderator identities for an official Jaal build.
//
//   cd packages/jaal_core && dart run tool/genesis.dart
//
// Run it ONCE, offline, on a machine you trust. Each 24-word phrase is printed
// exactly once: write it on paper and keep the three apart (they should belong
// to three different trusted people). Only the PUBLIC keys are written to
// lib/src/moderation/genesis_keys.dart, which is safe to commit.
//
// Pass --force to replace keys that are already set (this splits the network
// from every client still shipping the old keys).
import 'dart:io';

import 'package:jaal_core/jaal_core.dart';

Future<void> main(List<String> args) async {
  final file = File('lib/src/moderation/genesis_keys.dart');
  if (GenesisKeys.roots.isNotEmpty && !args.contains('--force')) {
    stderr.writeln('genesis keys are already set (${GenesisKeys.roots.length}). '
        'Use --force to replace them.');
    exitCode = 1;
    return;
  }

  final roots = <String>[];
  for (var i = 1; i <= 3; i++) {
    final id = await RootIdentity.generate();
    roots.add(id.id);
    stdout
      ..writeln('')
      ..writeln('══ genesis moderator #$i ══  ·${id.fingerprint}')
      ..writeln('root key : ${id.id}')
      ..writeln('phrase   : ${id.recoveryPhrase}')
      ..writeln('→ write this phrase down now. It will not be shown again.');
  }

  await file.writeAsString('''
/// The three genesis moderator root keys shipped with the official app.
/// Generated by tool/genesis.dart on ${DateTime.now().toUtc().toIso8601String().substring(0, 10)}.
/// Public keys only — the recovery phrases were shown once, offline.
abstract final class GenesisKeys {
  static const Set<String> roots = {
${roots.map((r) => "    '$r',").join('\n')}
  };
}
''');
  stdout
    ..writeln('')
    ..writeln('wrote ${file.path}. Restore each phrase in the Jaal app '
        '("i have a recovery phrase") on the moderator\'s own phone.');
}
